// Seletor de foto de mentira para os testes: devolve o que o teste mandar, sem abrir nenhum seletor do navegador.
import 'dart:typed_data';

import 'package:entrelinhas/shared/foto/seletor_de_foto.dart';

/// PNG de 1x1 pixel (válido), para a prévia ter bytes de imagem de verdade.
final pngMinimo = Uint8List.fromList(const [
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, //
  0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
  0x0D, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0xF0,
  0x1F, 0x00, 0x05, 0x00, 0x01, 0xFF, 0x89, 0x99, 0x3D, 0x1D, 0x00, 0x00,
  0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
]);

class SeletorFalso implements SeletorDeFoto {
  SeletorFalso({this.escolha});

  /// O que a "pessoa" escolhe; `null` = fechou o seletor sem escolher.
  FotoEscolhida? escolha;
  Object? falha;
  int chamadas = 0;

  @override
  Future<FotoEscolhida?> escolher() async {
    chamadas++;
    if (falha != null) throw falha!;
    return escolha;
  }
}

FotoEscolhida fotoDeTeste({
  String nome = 'minha-foto.png',
  String tipo = 'image/png',
  Uint8List? bytes,
}) => FotoEscolhida(bytes: bytes ?? pngMinimo, nome: nome, tipo: tipo);
